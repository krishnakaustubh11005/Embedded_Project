#!/usr/bin/env python3
"""Convert short sound recordings (mp3/mp4/wav...) into C arrays for the Pico.

Each file is decoded with ffmpeg to mono 22 050 Hz, the quiet lead-in is
trimmed (so the sound starts exactly when the hit lands), the length is capped,
the end is faded out, the level is normalised and it is stored as signed 8-bit
PCM -- one byte per sample, about 22 KB per second of audio in flash.

Usage (from the project root):
    python3 tools/audio_to_c.py                      # default kick/punch files
    python3 tools/audio_to_c.py --ffmpeg /path/to/ffmpeg kick=my_kick.mp3 ...

Then rebuild the firmware. The names kick, punch1 and punch2 must stay the same
because src/audio/sound.c refers to clip_kick, clip_punch1 and clip_punch2.
"""
import argparse
import array
import os
import shutil
import subprocess
import sys

RATE = 22050
MAX_SECONDS = 0.45
FADE_SECONDS = 0.04
PREROLL_SECONDS = 0.01
ONSET_FRACTION = 0.25
PEAK = 120


def find_ffmpeg(explicit):
    """Return a usable ffmpeg executable path or exit with a helpful message."""
    if explicit:
        return explicit
    found = shutil.which("ffmpeg")
    if found:
        return found
    try:
        import imageio_ffmpeg  # pip install imageio-ffmpeg bundles a static ffmpeg
        return imageio_ffmpeg.get_ffmpeg_exe()
    except ImportError:
        sys.exit("ffmpeg not found: sudo apt install ffmpeg  (or pip install imageio-ffmpeg)")


def decode(ffmpeg, path):
    """Decode any audio/video file to a list of mono 16-bit samples at RATE."""
    raw = subprocess.run([ffmpeg, "-v", "error", "-i", path, "-vn", "-ac", "1", "-ar", str(RATE),
                          "-f", "s16le", "-"], check=True, capture_output=True).stdout
    samples = array.array("h")
    samples.frombytes(raw)
    if sys.byteorder == "big":
        samples.byteswap()
    return list(samples)


def shape(samples):
    """Trim the lead-in, cap the length, fade out and scale to signed 8-bit."""
    peak = max(1, max(abs(s) for s in samples))
    start = next(i for i, s in enumerate(samples) if abs(s) >= peak * ONSET_FRACTION)
    start = max(0, start - int(PREROLL_SECONDS * RATE))
    clip = samples[start:start + int(MAX_SECONDS * RATE)]
    fade = min(len(clip), int(FADE_SECONDS * RATE))
    for i in range(fade):
        clip[len(clip) - fade + i] = clip[len(clip) - fade + i] * (fade - i) / fade
    scale = PEAK / max(1, max(abs(s) for s in clip))
    return [max(-127, min(127, round(s * scale))) for s in clip]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ffmpeg", help="path to an ffmpeg executable")
    parser.add_argument("--out", default="src/audio/duel_clips.c")
    parser.add_argument("clips", nargs="*", default=["kick=kick.mp4", "punch1=punch1.mp4", "punch2=punch2.mp4"],
                        help="name=file pairs")
    args = parser.parse_args()
    ffmpeg = find_ffmpeg(args.ffmpeg)
    lines = ["/* GENERATED by tools/audio_to_c.py -- do not edit by hand.",
             f" * Signed 8-bit mono PCM at {RATE} Hz, stored in flash (const). */",
             "#include \"audio/clips.h\"", ""]
    for pair in args.clips:
        name, path = pair.split("=", 1)
        pcm = shape(decode(ffmpeg, path))
        lines.append(f"/* {os.path.basename(path)}: {len(pcm)} samples, {len(pcm) / RATE * 1000:.0f} ms */")
        lines.append(f"static const int8_t {name}_data[{len(pcm)}]={{")
        for i in range(0, len(pcm), 24):
            lines.append("    " + ",".join(str(v) for v in pcm[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"const Clip clip_{name}={{{name}_data,{len(pcm)}u}};")
        lines.append("")
        print(f"{name}: {path} -> {len(pcm)} samples ({len(pcm) / RATE:.2f} s)")
    with open(args.out, "w") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
